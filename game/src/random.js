// A small seeded random source (mulberry32) so a seed always replays the
// same game: the same ?seed= gives the same moths, the same blooms and the
// same screenshots. Nothing here touches Math.random, so a run is fully
// determined by its seed.
export function createRandom(seed) {
  let state = seed >>> 0;
  function next() {
    state |= 0;
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }
  return {
    next,
    range(min, max) {
      return min + next() * (max - min);
    },
    int(min, max) {
      return Math.floor(this.range(min, max + 1));
    },
    pick(list) {
      return list[Math.floor(next() * list.length)];
    },
    /** Fisher-Yates, in place, so a wave's roster arrives in a varied order. */
    shuffle(list) {
      for (let i = list.length - 1; i > 0; i -= 1) {
        const j = Math.floor(next() * (i + 1));
        [list[i], list[j]] = [list[j], list[i]];
      }
      return list;
    },
    /** True with the given probability; used for pickup drops. */
    chance(p) {
      return next() < p;
    },
  };
}
